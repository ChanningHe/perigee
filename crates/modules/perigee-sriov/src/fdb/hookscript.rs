//! Hookscript fallback: let PVE add/remove FDB entries at guest start/stop.
//!
//! The script is a thin shim around `perigee sriov fdb-hook`, so the FDB
//! logic lives in one place (see [`super::hook`]).

use anyhow::{bail, Context, Result};
use std::path::Path;
use tracing::info;

/// Where the hookscript goes when a profile sets no `output_path`; this is
/// the `local:snippets/` storage on a default PVE install.
pub const DEFAULT_HOOKSCRIPT_PATH: &str = "/var/lib/vz/snippets/perigee-bridgefix.sh";

/// Marker identifying a file as ours, so a user's own snippet at the same
/// path is never overwritten.
const MARKER: &str = "# Perigee FDB hookscript";

/// Upper bound on one hook run (coreutils `timeout`): a hung pmxcfs read or
/// `bridge` call would otherwise stall the guest start indefinitely. After the
/// grace period the hook is killed outright.
const HOOK_TIMEOUT_SECS: u32 = 30;
const HOOK_KILL_GRACE_SECS: u32 = 5;

/// Write the hookscript to `output_path`, invoking `perigee_bin`.
pub fn generate_hookscript(output_path: &Path, perigee_bin: &Path) -> Result<()> {
    match std::fs::read(output_path) {
        Ok(existing) if !String::from_utf8_lossy(&existing).contains(MARKER) => bail!(
            "{} exists and was not generated by perigee; refusing to overwrite",
            output_path.display()
        ),
        Ok(_) => {}
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
        Err(e) => {
            return Err(e).with_context(|| format!("read {}", output_path.display()));
        }
    }
    if let Some(parent) = output_path.parent() {
        std::fs::create_dir_all(parent).with_context(|| format!("create {}", parent.display()))?;
    }
    std::fs::write(output_path, render_hookscript(perigee_bin))
        .with_context(|| format!("write {}", output_path.display()))?;

    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(output_path, std::fs::Permissions::from_mode(0o755))?;
    }

    info!(path = %output_path.display(), "hookscript generated");
    Ok(())
}

/// Render the hookscript text. It must always exit 0: PVE aborts the guest
/// start when a `pre-start` hook fails.
fn render_hookscript(perigee_bin: &Path) -> String {
    format!(
        r#"#!/bin/sh
{MARKER} - auto-generated, do not edit.
# Attach: qm set <vmid> --hookscript <storage>:snippets/<file>  (pct set for CTs)
# Acts on SR-IOV profiles whose FDB mode is "hookscript".
timeout -k {HOOK_KILL_GRACE_SECS} {HOOK_TIMEOUT_SECS} "{bin}" sriov fdb-hook "$1" "$2" || true
exit 0
"#,
        bin = perigee_bin.display(),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scratch(name: &str) -> std::path::PathBuf {
        let dir =
            std::env::temp_dir().join(format!("perigee-hook-{}-{}", std::process::id(), name));
        let _ = std::fs::remove_dir_all(&dir);
        dir.join("hook.sh")
    }

    #[test]
    fn hookscript_always_exits_zero() {
        let script = render_hookscript(Path::new("/usr/local/bin/perigee"));
        assert!(script.contains(r#""/usr/local/bin/perigee" sriov fdb-hook "$1" "$2" || true"#));
        assert!(script.trim_end().ends_with("exit 0"));
    }

    #[test]
    fn hook_runtime_is_bounded() {
        // A hung pmxcfs or `bridge` call must not stall `qm start` forever.
        let script = render_hookscript(Path::new("/usr/local/bin/perigee"));
        assert!(script.contains(r#"timeout -k 5 30 "/usr/local/bin/perigee" sriov fdb-hook"#));
    }

    #[test]
    fn regenerates_own_script_but_not_foreign_file() {
        let path = scratch("overwrite");
        let bin = Path::new("/usr/local/bin/perigee");
        generate_hookscript(&path, bin).unwrap();
        generate_hookscript(&path, bin).unwrap();

        std::fs::write(&path, "#!/bin/sh\necho user hook\n").unwrap();
        assert!(generate_hookscript(&path, bin).is_err());

        // A non-UTF-8 foreign file is still foreign.
        let binary = path.with_file_name("binary.sh");
        std::fs::write(&binary, [0xff, 0xfe, 0x00]).unwrap();
        assert!(generate_hookscript(&binary, bin).is_err());
        assert_eq!(std::fs::read(&binary).unwrap(), [0xff, 0xfe, 0x00]);
        assert!(std::fs::read_to_string(&path)
            .unwrap()
            .contains("user hook"));
    }
}
